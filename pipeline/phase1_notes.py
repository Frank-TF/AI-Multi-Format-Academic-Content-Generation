@dataclass
class TopicNote:
    title: str
    core: str
    definitions: list[tuple[str, str]]
    evidence: list[str]
    example: str
    bullets: list[str]


@dataclass
class Question:
    kind: str
    prompt: str
    answer: str
    options: list[str] = field(default_factory=list)


@dataclass
class StudyGuide:
    title: str
    source_title: str
    author: str
    uid: str
    course: str
    generated: str
    abstract: str
    keywords: list[str]
    topics: list[TopicNote]
    revision_points: list[str]
    matrix: list[tuple[str, str, str]]
    questions: list[Question]
    reviser: list[str]
    glossary: list[tuple[str, str]]
    stats: dict
    markdown: str = ""

    @property
    def word_count(self) -> int:
        return len(self.markdown.split())

    def to_markdown(self) -> str:
        lines: list[str] = []
        lines.append(f"# COMPREHENSIVE STUDY GUIDE: {self.title.upper()}")
        lines.append("")
        lines.append(f"**{self.source_title}**")
        lines.append("")
        lines.append(f"*{self.author} | UID: {self.uid} | Subject Code: {self.course}*")
        lines.append("")
        lines.append("## Abstract")
        lines.append(self.abstract)
        lines.append("")
        lines.append("**Keywords:** " + "; ".join(self.keywords))
        lines.append("")
        lines.append("## 1. Study Notes & Core Concepts")
        for i, topic in enumerate(self.topics, 1):
            lines.append("")
            lines.append(f"### Topic {i}: {topic.title}")
            lines.append(f"**Core concept.** {topic.core}")
            for term, definition in topic.definitions:
                lines.append(f"- **{term}:** {definition}")
            for pill in topic.bullets:
                lines.append(f"- {pill}")
            lines.append(f"**Practical example.** {topic.example}")
        lines.append("")
        lines.append("## 2. Structured Revision Points")
        lines.append("### Key Facts and Statistics")
        for point in self.revision_points:
            lines.append(f"- {point}")
        lines.append("")
        lines.append("### Sequential Process: Secure IoT Software Update (SUIT)")
        for step in _suit_steps():
            lines.append(f"- {step}")
        lines.append("")
        lines.append("### Comparative Framing: Symmetric vs Asymmetric Cryptography")
        lines.append(
            "- **Symmetric cryptography (ChaCha20, AES):** one shared secret key; fast, "
            "energy-efficient and ideal for bulk payloads, but key distribution is hard."
        )
        lines.append(
            "- **Asymmetric cryptography (ECC, post-quantum schemes):** a public/private "
            "key pair enables signatures and key exchange, but costs more CPU, memory and energy."
        )
        lines.append("")
        lines.append("## 3. Quick Revision Matrix")
        lines.append("| Research Field / Domain | Core Definition | Primary IoT Use Cases |")
        lines.append("|---|---|---|")
        for name, definition, use_case in self.matrix:
            lines.append(f"| {name} | {definition} | {use_case} |")
        lines.append("")
        lines.append("## 4. Exam-Oriented Question Bank")
        for kind in ("Short-Answer / Conceptual", "Practical / Scenario-Based", "Multiple-Choice"):
            lines.append("")
            lines.append(f"### {kind} Questions")
            n = 0
            for q in self.questions:
                if q.kind != kind:
                    continue
                n += 1
                lines.append(f"{n}. {q.prompt}")
                for opt in q.options:
                    lines.append(f"   - {opt}")
                lines.append(f"   **Answer:** {q.answer}")
        lines.append("")
        lines.append("## 5. Last-Minute Reviser")
        for point in self.reviser:
            lines.append(f"- {point}")
        lines.append("")
        lines.append("---")
        lines.append(f"*Generated by the AI-Assisted Multi-Format Content Studio on {self.generated}.*")
        self.markdown = "\n".join(lines)
        return self.markdown


def _suit_steps() -> list[str]:
    return [
        "Phase 0 - Commission: provision the device with a public key and symmetric master credentials out of band.",
        "Phase 1 - Build: compile the new firmware into a deployment-ready image.",
        "Phase 2 - Publish and sign: create a signed manifest containing hashes and publish the package.",
        "Phase 3 - Fetch: the constrained device polls and downloads the update package.",
        "Phase 4 - Authenticate and verify: check the signature and SHA-256 hashes before installation.",
        "Phase 5 - Install or abort: install only on success; otherwise abort and raise a security alert.",
    ]


def _iot_mode(text: str) -> bool:
    low = text.lower()
    return low.count(" internet of things ") > 5 or low.count(" iot ") > 120


def _definition_sentences(sentences: Iterable[str], terms: Iterable[str]) -> list[tuple[str, str]]:
    term_list = [t.lower() for t in terms]
    out: list[tuple[str, str]] = []
    for sent in sentences:
        low = sent.lower()
        for term in term_list:
            if term not in low:
                continue
            m = re.search(
                r"([A-Z][A-Za-z0-9 ()\-/]{2,45}?)\s+(?:is|are|refers to|means|describes|denotes)\s+(.{25,220})",
                sent,
            )
            if m:
                label = m.group(1).strip(" ,;:")
                definition = m.group(2).strip(" .;:")
                if 2 <= len(label.split()) <= 6:
                    out.append((label, definition[:220]))
                    break
    return out


def _generic_topics(doc: SourceDocument, index: TfidfIndex) -> list[TopicNote]:
    keywords = [k for k, _ in extract_keywords(doc.text, 18) if " " not in k]
    topics: list[TopicNote] = []
    for kw in keywords[:4]:
        ranked = index.rank(kw, limit=6, diversity=0.30)
        evidence = [sanitise_sentence(s.text) for s in ranked if is_good_sentence(sanitise_sentence(s.text))]
        if len(evidence) < 2:
            continue
        core = evidence[0]
        definitions = _definition_sentences(evidence, [kw])[:2]
        if not definitions:
            definitions = [(kw.title(), truncate(evidence[0], 170))]
        example = next(
            (e for e in evidence if re.search(r"(for example|for instance|e\.g\.|such as)", e.lower())),
            evidence[-1],
        )
        topics.append(TopicNote(
            title=f"{kw.replace('-', ' ').title()} in the Source Material",
            core=core,
            definitions=definitions,
            evidence=evidence,
            example=example,
            bullets=[truncate(e, 180) for e in evidence[1:5]],
        ))
    return topics[:4]


def _generate_questions(glossary: list[tuple[str, str]], topics: list[TopicNote]) -> list[Question]:
    questions: list[Question] = []
    short_terms = glossary[:5]
    for term, definition in short_terms:
        questions.append(Question(
            "Short-Answer / Conceptual",
            f"Define {term} and explain why it matters in a constrained IoT system.",
            truncate(definition, 260),
        ))
    scenarios = [
        ("A smart-city project deploys battery-powered environmental sensors in a valley with no cellular coverage. "
         "Identify the main energy, bandwidth and maintenance constraints and propose an architecture.",
         "Use low-power wide-area networking or multi-hop mesh, duty-cycle the radio, process data at an edge gateway, "
         "and use energy harvesting with intermittent-computing support."),
        ("An industrial control loop receives sensor packets 200 ms late during network congestion, causing instability. "
         "Explain the cause and propose a mitigation.",
         "The delay violates the control loop's timing budget. Move the controller to the edge, prioritise its traffic, "
         "and design the controller to tolerate bounded jitter."),
        ("A manufacturer discovers a remotely exploitable vulnerability in an insulin pump. Outline a safe remediation lifecycle.",
         "Provision keys, build and sign a SUIT manifest, distribute the package, verify signature and hashes on-device, "
         "install atomically, and abort with an alert if verification fails."),
    ]
    for prompt, answer in scenarios:
        questions.append(Question("Practical / Scenario-Based", prompt, answer))

    mcqs = [
        ("Which open-source operating system is designed for microcontrollers that cannot run Linux?",
         ["Android Embedded", "RIOT", "Windows IoT Core", "Ubuntu Touch"], "B) RIOT"),
        ("Which property makes ChaCha20 attractive on microcontrollers without hardware AES acceleration?",
         ["It removes the need for keys", "It is fast in software", "It increases key length to 1024 bits", "It needs no memory"],
         "B) It is fast in software"),
        ("What does federated learning keep on the device?",
         ["Only the final model", "Raw training data", "The central server logs", "The encryption key"],
         "B) Raw training data"),
        ("Which update standard defines a signed manifest for constrained devices?",
         ["SUIT", "SMTP", "X10", "HTML5"], "A) SUIT"),
    ]
    for prompt, options, answer in mcqs:
        questions.append(Question("Multiple-Choice", prompt, answer, options))
    return questions


def generate_study_guide(doc: SourceDocument, meta: ProjectMeta) -> StudyGuide:
    """Build the Phase 1 deliverable from the source document."""
    sentences = [
        sanitise_sentence(s) for s in split_sentences(doc.text)
        if is_good_sentence(sanitise_sentence(s))
    ]
    sentences = unique_sentences(sentences, 0.86)
    index = TfidfIndex(sentences)
    iot = _iot_mode(doc.text)
    generated = datetime.now().strftime("%d %B %Y")

    if iot:
        topics: list[TopicNote] = []
        for spec in IOT_TOPICS:
            ranked = index.rank(spec.query, limit=8, diversity=0.32)
            evidence = []
            for item in ranked:
                s = sanitise_sentence(item.text)
                if is_good_sentence(s) and s not in evidence:
                    evidence.append(s)
            defs = _definition_sentences(evidence, [w for w in content_words(spec.title) if len(w) > 4])
            topic_glossary = _match_glossary(spec.title)
            definitions = topic_glossary[:3] if topic_glossary else defs[:3]
            if not definitions:
                definitions = [(spec.title.split()[0], truncate(spec.core, 190))]
            # The curated pills carry the reviewed facts. Retrieved evidence is
            # kept for traceability but not pasted into the guide, because raw
            # PDF lines can include running heads or table-of-contents debris.
            bullets = list(spec.pills)
            topics.append(TopicNote(
                title=spec.title,
                core=spec.core,
                definitions=definitions,
                evidence=evidence[:4],
                example=spec.example,
                bullets=bullets[:5],
            ))
        glossary = list(IOT_GLOSSARY)
        matrix = [(f.name, f.definition, f.use_case) for f in IOT_FIELDS]
        revision_points = list(IOT_FACTS)
        reviser = [
            "IoT passed the tipping point in 2020: more than half of all connected devices are IoT devices.",
            "Low-end nodes are constrained by energy first, then memory, CPU and network throughput.",
            "Use symmetric ciphers for bulk data and asymmetric primitives for signatures and key exchange.",
            "Federated learning shares model updates, not raw personal data.",
            "Secure updates require a signed manifest, hash verification and an atomic install/abort decision.",
            "The cloud-edge-thing continuum trades centralisation for latency, bandwidth and privacy.",
            "Digital sovereignty concerns infrastructure and standards, not only applications.",
            "Open standards and open source reduce lock-in and support long device lifetimes.",
        ]
        keywords = ["Internet of Things", "edge computing", "lightweight cryptography",
                    "federated learning", "digital sovereignty", "SUIT", "RIOT OS"]
        abstract = (
            "This study guide synthesises Inria White Book No. 05 on the Internet of Things. "
            "It traces the transition from ubiquitous computing to a global installed base of roughly "
            "10 billion devices, which crossed the 50% tipping point in 2020. It then examines the "
            "societal challenges of privacy, sovereignty and sustainability, and the technical "
            "challenges created by severe energy and memory constraints. Finally, it maps the research "
            "fields of the cloud-edge-thing continuum and condenses the material into definitions, a "
            "revision matrix, a question bank and a last-minute reviser."
        )
    else:
        topics = _generic_topics(doc, index)
        if not topics:
            raise ValueError("Unable to identify coherent topics in this document.")
        glossary_pairs = _definition_sentences(sentences, [k for k, _ in extract_keywords(doc.text, 12)])
        glossary = dedupe_pairs(glossary_pairs)[:10]
        if len(glossary) < 5:
            for topic in topics:
                glossary.extend(topic.definitions)
        glossary = dedupe_pairs(glossary)[:10]
        matrix = [(t.title, truncate(t.core, 150), truncate(t.example, 130)) for t in topics]
        revision_points = [truncate(s, 230) for s in sentences if any(ch.isdigit() for ch in s)][:8]
        revision_points += [truncate(t.core, 210) for t in topics][:4]
        reviser = [truncate(t.core, 180) for t in topics]
        keywords = [k for k, _ in extract_keywords(doc.text, 7)]
        abstract = " ".join(truncate(t.core, 260) for t in topics[:4])
        abstract = (
            f"This study guide condenses {doc.words:,} words from the source into four core topics, "
            "a glossary, a revision matrix, an examination-oriented question bank and a "
            "last-minute reviser. " + abstract
        )

    questions = _generate_questions(glossary, topics)
    stats = {
        "source_words": doc.words,
        "source_pages": doc.pages,
        "source_sentences": len(split_sentences(doc.text)),
        "summary_words": 0,
        "compression_ratio": 0.0,
        "reading_time_min": 0,
        "topics": len(topics),
        "definitions": len(glossary),
        "matrix_rows": len(matrix),
        "questions": len(questions),
        "revision_points": len(revision_points),
    }
    guide = StudyGuide(
        title=meta.title,
        source_title=doc.title,
        author=meta.author,
        uid=meta.uid,
        course=meta.course,
        generated=generated,
        abstract=abstract,
        keywords=keywords,
        topics=topics,
        revision_points=revision_points,
        matrix=matrix,
        questions=questions,
        reviser=reviser,
        glossary=glossary,
        stats=stats,
    )
    markdown = guide.to_markdown()
    guide.stats["summary_words"] = len(markdown.split())
    guide.stats["compression_ratio"] = round(100 * guide.stats["summary_words"] / max(1, doc.words), 1)
    guide.stats["reading_time_min"] = max(1, round(guide.stats["summary_words"] / 200))
    # Readability is measured on continuous prose only: Markdown table rows and
    # headings are not sentences and would otherwise inflate the sentence length.
    prose_blocks = [guide.abstract]
    for topic in topics:
        prose_blocks.extend([topic.core, topic.example])
        prose_blocks.extend(topic.bullets)
    prose_blocks.extend(revision_points)
    prose_blocks.extend(reviser)
    prose = " ".join(prose_blocks)
    guide.stats["prose_words"] = len(prose.split())
    guide.stats["readability"] = readability(prose)
    return guide


def _match_glossary(title: str) -> list[tuple[str, str]]:
    low = title.lower()
    mapping = {
        "introduction": ["Cyber-Physical Systems", "Web of Things", "Edge Computing"],
        "societal": ["Digital Sovereignty", "Surveillance Capitalism", "Federated Learning"],
        "scientific": ["Lightweight Cryptography", "Intermittent Computing", "Object Security"],
        "architecture": ["Edge Computing", "Web of Things", "Cyber-Physical Systems"],
    }
    for key, names in mapping.items():
        if key in low:
            return [(n, d) for n, d in IOT_GLOSSARY if n.startswith(tuple(names))]
    return []


def dedupe_pairs(pairs: list[tuple[str, str]]) -> list[tuple[str, str]]:
    seen, out = set(), []
    for label, definition in pairs:
        key = label.lower().strip()
        if key and key not in seen:
            seen.add(key)
            out.append((label, definition))
    return out
